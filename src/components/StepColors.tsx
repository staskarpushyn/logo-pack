import React, { useRef, useState } from 'react';
import {
  Plus,
  Copy,
  X,
  ChevronUp,
  ChevronDown,
  Upload,
  ArrowLeft,
  ArrowRight,
  SkipForward,
  Check,
  AlertTriangle,
  Sparkles,
  RefreshCw,
} from 'lucide-react';
import type { BrandColor, CmykValues, Locale, LogoAsset } from '../types';
import { COPY } from '../i18n';
import {
  contrastRatio,
  generateHarmoniousColor,
  guessColorName,
  hexToCmyk,
  hexToRgb,
  isAutoGeneratedColorName,
  normalizeHex,
  regenerateMatchingColor,
  relativeLuminance,
  type HarmonyStrategy,
} from '../utils/color';
import { auditSvg, recolorSvg } from '../utils/svgEngine';
import { importVectorFile } from '../utils/vectorImport';
import { ToggleSwitch } from './ToggleSwitch';

interface StepColorsProps {
  locale: Locale;
  assets: LogoAsset[];
  colors: BrandColor[];
  setColors: React.Dispatch<React.SetStateAction<BrandColor[]>>;
  bwEditions: boolean;
  setBwEditions: (v: boolean) => void;
  keepOriginal: boolean;
  setKeepOriginal: (v: boolean) => void;
  onBack: () => void;
  onSkip: () => void;
  onNext: () => void;
}

export const StepColors: React.FC<StepColorsProps> = ({
  locale,
  assets,
  colors,
  setColors,
  bwEditions,
  setBwEditions,
  keepOriginal,
  setKeepOriginal,
  onBack,
  onSkip,
  onNext,
}) => {
  const t = COPY[locale];
  // All color cards start collapsed by default (Screenshot 3); user opens needed ones independently
  const [expandedIds, setExpandedIds] = useState<Record<string, boolean>>({});
  const [regenCounts, setRegenCounts] = useState<Record<string, number>>({});
  const [harmStep, setHarmStep] = useState(0);
  const [copiedId, setCopiedId] = useState<string | null>(null);
  const [isDroppingPalette, setIsDroppingPalette] = useState(false);
  const [paletteError, setPaletteError] = useState('');
  const paletteFileRef = useRef<HTMLInputElement>(null);

  const primaryAsset = assets.find((a) => a.role === 'primary') ?? assets[0];

  const toggleExpand = (id: string) => {
    setExpandedIds((prev) => ({ ...prev, [id]: !prev[id] }));
  };

  const addManualColor = () => {
    const hex = '#FA5008';
    const newC: BrandColor = {
      id: `${Date.now()}-${Math.random().toString(36).slice(2, 6)}`,
      name: guessColorName(hex, colors.length),
      hex,
      cmykMode: 'auto',
      cmyk: hexToCmyk(hex),
      useAsLogo: true,
      useAsBackground: true,
    };
    setColors((prev) => [...prev, newC]);
    setExpandedIds((prev) => ({ ...prev, [newC.id]: true }));
  };

  const addHarmoniousColor = (strategy: HarmonyStrategy = 'auto') => {
    const picked = generateHarmoniousColor(colors, strategy, harmStep);
    setHarmStep((s) => s + 1);
    const lum = relativeLuminance(picked.hex);
    const newC: BrandColor = {
      id: `${Date.now()}-${Math.random().toString(36).slice(2, 6)}`,
      name: picked.name,
      hex: picked.hex,
      cmykMode: 'auto',
      cmyk: hexToCmyk(picked.hex),
      useAsLogo: lum < 0.72,
      useAsBackground: true,
    };
    setColors((prev) => [...prev, newC]);
    setExpandedIds((prev) => ({ ...prev, [newC.id]: true }));
  };

  const handleImportPaletteFile = async (file: File | undefined) => {
    if (!file) return;
    setPaletteError('');
    try {
      const imported = await importVectorFile(file);
      const res = auditSvg(imported.svgContent);
      const existing = new Set(colors.map((c) => c.hex.toUpperCase()));
      const added: BrandColor[] = [];
      res.colors.forEach((hex, idx) => {
        const up = hex.toUpperCase();
        if (!existing.has(up) && colors.length + added.length < 24) {
          existing.add(up);
          added.push({
            id: `${Date.now()}-${idx}-${Math.random().toString(36).slice(2, 5)}`,
            name: guessColorName(up, colors.length + added.length),
            hex: up,
            cmykMode: 'auto',
            cmyk: hexToCmyk(up),
            useAsLogo: true,
            useAsBackground: true,
          });
        }
      });
      if (added.length) {
        setColors((prev) => [...prev, ...added]);
        setExpandedIds((prev) => ({ ...prev, [added[0].id]: true }));
      } else {
        setPaletteError(
          locale === 'ua'
            ? 'У файлі не знайдено нових кольорів (або вони вже є в палітрі).'
            : 'No new distinct colors found in that file.',
        );
      }
    } catch (err) {
      setPaletteError(err instanceof Error ? err.message : 'Palette import failed');
    }
  };

  const regenerateOneColor = (id: string, e: React.MouseEvent) => {
    e.stopPropagation();
    const count = regenCounts[id] ?? 0;
    const picked = regenerateMatchingColor(colors, id, count);
    setRegenCounts((prev) => ({ ...prev, [id]: count + 1 }));
    setColors((prev) =>
      prev.map((item) =>
        item.id === id
          ? {
              ...item,
              hex: picked.hex,
              name: isAutoGeneratedColorName(item.name) ? picked.name : picked.name,
              cmyk: item.cmykMode === 'auto' ? hexToCmyk(picked.hex) : item.cmyk,
            }
          : item,
      ),
    );
  };

  const updateColor = (id: string, patch: Partial<BrandColor>) => {
    setColors((prev) => prev.map((c) => (c.id === id ? { ...c, ...patch } : c)));
  };

  const handleCopyHex = (c: BrandColor, e: React.MouseEvent) => {
    e.stopPropagation();
    navigator.clipboard?.writeText(c.hex).catch(() => {});
    setCopiedId(c.id);
    setTimeout(() => setCopiedId((cur) => (cur === c.id ? null : cur)), 1100);
  };

  const logoInks = colors.filter((c) => c.useAsLogo);
  const bgSwatches = [
    { id: 'bg-white', name: 'White', hex: '#FFFFFF' },
    ...colors.filter((c) => c.useAsBackground && c.hex.toUpperCase() !== '#FFFFFF'),
  ];

  return (
    <div className="space-y-6">
      <div>
        <h1 className="text-2xl sm:text-3xl font-bold text-[#1f1f1f]">
          {locale === 'ua' ? (
            <>
              Палітра <span className="italic font-normal">бренду</span>
            </>
          ) : (
            <>
              Brand <span className="italic font-normal">colors</span>
            </>
          )}
        </h1>
        <p className="mt-1.5 text-sm text-[#6b6b6b]">{t.colorsSubtitle}</p>
      </div>

      {/* Global option cards */}
      <div className="space-y-3">
        <div className="rounded-xl border border-[#e5e3dc] bg-white px-4 py-3.5">
          <ToggleSwitch
            size="sm"
            checked={bwEditions}
            onChange={setBwEditions}
            label={t.bwToggle}
            description={t.bwHint}
          />
        </div>
        <div className="rounded-xl border border-[#e5e3dc] bg-white px-4 py-3.5">
          <ToggleSwitch
            size="sm"
            checked={keepOriginal}
            onChange={setKeepOriginal}
            label={t.keepOriginal}
            description={t.keepOriginalHint}
          />
        </div>
      </div>

      {/* Horizontal Full-Width Brand Color Accordion Cards (matching Screenshot 2 specs!) */}
      <div className="space-y-3.5">
        {colors.map((c) => {
          const rgb = hexToRgb(c.hex);
          const cmyk = c.cmykMode === 'manual' ? c.cmyk : hexToCmyk(c.hex);
          const isExpanded = !!expandedIds[c.id];
          const isLightSwatch = relativeLuminance(c.hex) > 0.55;
          const bannerFg = isLightSwatch ? '#1F1F1F' : '#FFFFFF';
          const bannerSub = isLightSwatch ? 'rgba(31,31,31,0.68)' : 'rgba(255,255,255,0.78)';

          return (
            <div
              key={c.id}
              className="rounded-xl border border-[#e5e3dc] bg-white overflow-hidden shadow-2xs"
            >
              {/* Colored header stays the EXACT same swatch color both collapsed and expanded */}
              <div
                onClick={() => toggleExpand(c.id)}
                className="px-4 py-3 flex items-center justify-between cursor-pointer transition-[filter] hover:brightness-[0.98]"
                style={{ backgroundColor: c.hex, color: bannerFg }}
              >
                <div className="min-w-0">
                  <div className="text-sm font-semibold truncate">{c.name}</div>
                  <div className="text-[11px] font-mono" style={{ color: bannerSub }}>
                    {c.hex}
                  </div>
                </div>
                <div className="flex items-center gap-1">
                  <button
                    type="button"
                    onClick={(e) => regenerateOneColor(c.id, e)}
                    className="rounded-md p-1.5 hover:bg-black/10"
                    title={
                      locale === 'ua'
                        ? 'Підібрати інший гармонійний відтінок для цього кольору'
                        : 'Regenerate a matching harmonious color'
                    }
                  >
                    <RefreshCw className="h-3.5 w-3.5" />
                  </button>
                  <button
                    type="button"
                    onClick={(e) => handleCopyHex(c, e)}
                    className="rounded-md p-1.5 hover:bg-black/10"
                    title="Copy HEX"
                  >
                    {copiedId === c.id ? (
                      <Check className="h-3.5 w-3.5" />
                    ) : (
                      <Copy className="h-3.5 w-3.5" />
                    )}
                  </button>
                  <button
                    type="button"
                    onClick={(e) => {
                      e.stopPropagation();
                      toggleExpand(c.id);
                    }}
                    className="rounded-md p-1.5 hover:bg-black/10"
                    title={isExpanded ? 'Collapse' : 'Expand'}
                  >
                    {isExpanded ? (
                      <ChevronUp className="h-3.5 w-3.5" />
                    ) : (
                      <ChevronDown className="h-3.5 w-3.5" />
                    )}
                  </button>
                  <button
                    type="button"
                    onClick={(e) => {
                      e.stopPropagation();
                      setColors((prev) => prev.filter((item) => item.id !== c.id));
                    }}
                    className="rounded-md p-1.5 hover:bg-black/10"
                    title="Remove"
                  >
                    <X className="h-3.5 w-3.5" />
                  </button>
                </div>
              </div>

              {isExpanded ? (
                <div className="p-4 space-y-4 bg-white">
                  <div className="grid grid-cols-1 md:grid-cols-12 gap-3.5 items-start">
                    {/* Color Name — uniform h-6 label row so all fields align horizontally! */}
                    <div className="md:col-span-3">
                      <div className="h-6 flex items-center justify-between mb-1.5">
                        <label className="text-[10px] uppercase tracking-wider font-semibold text-[#6b6b6b]">
                          Color Name
                        </label>
                      </div>
                      <div className="flex items-center rounded-lg border border-[#e5e3dc] bg-white pr-1.5 h-10 focus-within:border-[#fa5008]">
                        <input
                          type="text"
                          value={c.name}
                          onChange={(e) => updateColor(c.id, { name: e.target.value })}
                          className="w-full h-full bg-transparent px-3 text-sm text-[#1f1f1f] focus:outline-none"
                        />
                        <button
                          type="button"
                          onClick={() => updateColor(c.id, { name: guessColorName(c.hex) })}
                          title={locale === 'ua' ? 'Автоматично назвати колір' : 'Auto-detect color name'}
                          className="rounded p-1 text-[#8e8e8e] hover:bg-[#f8f6f1] hover:text-[#fa5008] transition shrink-0"
                        >
                          <Sparkles className="h-3.5 w-3.5" />
                        </button>
                      </div>
                    </div>

                    {/* HEX / Digital */}
                    <div className="md:col-span-4">
                      <div className="h-6 flex items-center justify-between mb-1.5">
                        <label className="text-[10px] uppercase tracking-wider font-semibold text-[#6b6b6b]">
                          HEX / Digital
                        </label>
                      </div>
                      <div className="flex items-center gap-2 rounded-lg border border-[#e5e3dc] bg-white px-2 h-10 focus-within:border-[#fa5008]">
                        <label
                          className="relative h-6 w-6 shrink-0 cursor-pointer rounded-md border border-black/15 overflow-hidden block"
                          style={{ backgroundColor: c.hex }}
                          title={locale === 'ua' ? 'Обрати колір' : 'Pick color'}
                        >
                          <input
                            type="color"
                            value={normalizeHex(c.hex) ?? '#FA5008'}
                            onChange={(e) => {
                              const hex = e.target.value.toUpperCase();
                              const autoName = isAutoGeneratedColorName(c.name)
                                ? guessColorName(hex)
                                : c.name;
                              updateColor(c.id, {
                                hex,
                                name: autoName,
                                cmyk: c.cmykMode === 'auto' ? hexToCmyk(hex) : c.cmyk,
                              });
                            }}
                            className="absolute inset-0 opacity-0 w-full h-full cursor-pointer"
                          />
                        </label>
                        <input
                          type="text"
                          value={c.hex}
                          onChange={(e) => {
                            const raw = e.target.value;
                            const norm = normalizeHex(raw);
                            const autoName =
                              norm && isAutoGeneratedColorName(c.name)
                                ? guessColorName(norm)
                                : c.name;
                            updateColor(c.id, {
                              hex: norm ?? raw,
                              name: autoName,
                              cmyk: norm && c.cmykMode === 'auto' ? hexToCmyk(norm) : c.cmyk,
                            });
                          }}
                          className="w-full bg-transparent text-xs font-mono text-[#1f1f1f] focus:outline-none"
                        />
                      </div>
                      <div className="mt-1 text-[10px] font-mono text-[#6b6b6b]">
                        RGB {rgb.r}, {rgb.g}, {rgb.b}
                      </div>
                    </div>

                    {/* CMYK % */}
                    <div className="md:col-span-5">
                      <div className="h-6 flex items-center justify-between mb-1.5">
                        <span className="text-[10px] uppercase tracking-wider font-semibold text-[#6b6b6b]">
                          CMYK %
                        </span>
                        <div className="inline-flex rounded-md border border-[#e5e3dc] bg-[#f8f6f1] p-0.5 text-[10px] font-medium">
                          <button
                            type="button"
                            onClick={() =>
                              updateColor(c.id, { cmykMode: 'auto', cmyk: hexToCmyk(c.hex) })
                            }
                            className={`rounded px-2 py-0.5 transition ${
                              c.cmykMode === 'auto'
                                ? 'bg-white text-[#1f1f1f] shadow-2xs'
                                : 'text-[#6b6b6b]'
                            }`}
                          >
                            {t.autoCmyk}
                          </button>
                          <button
                            type="button"
                            onClick={() => updateColor(c.id, { cmykMode: 'manual' })}
                            className={`rounded px-2 py-0.5 transition ${
                              c.cmykMode === 'manual'
                                ? 'bg-white text-[#1f1f1f] shadow-2xs'
                                : 'text-[#6b6b6b]'
                            }`}
                          >
                            {t.manualCmyk}
                          </button>
                        </div>
                      </div>
                      <div className="grid grid-cols-4 gap-1.5">
                        {(['c', 'm', 'y', 'k'] as Array<keyof CmykValues>).map((ch) => (
                          <div
                            key={ch}
                            className="flex items-center rounded-lg border border-[#e5e3dc] bg-white px-2 h-10"
                          >
                            <span className="text-[10px] font-mono uppercase text-[#8e8e8e] mr-1">
                              {ch}
                            </span>
                            <input
                              type="number"
                              min={0}
                              max={100}
                              disabled={c.cmykMode === 'auto'}
                              value={c.cmykMode === 'auto' ? hexToCmyk(c.hex)[ch] : c.cmyk[ch]}
                              onChange={(e) => {
                                const val = Math.min(100, Math.max(0, Number(e.target.value) || 0));
                                updateColor(c.id, { cmyk: { ...c.cmyk, [ch]: val } });
                              }}
                              className="w-full bg-transparent text-xs font-mono text-right text-[#1f1f1f] disabled:text-[#6b6b6b] focus:outline-none"
                            />
                          </div>
                        ))}
                      </div>
                    </div>
                  </div>

                  {/* Role switches stay RIGHT-aligned in BOTH collapsed and expanded states */}
                  <div className="pt-2.5 border-t border-[#eceae5] flex flex-wrap items-center justify-end gap-5">
                    <ToggleSwitch
                      size="xs"
                      labelPosition="right"
                      checked={c.useAsLogo}
                      onChange={(v) => updateColor(c.id, { useAsLogo: v })}
                      label={t.useAsLogo}
                    />
                    <ToggleSwitch
                      size="xs"
                      labelPosition="right"
                      checked={c.useAsBackground}
                      onChange={(v) => updateColor(c.id, { useAsBackground: v })}
                      label={t.useAsBg}
                    />
                  </div>
                </div>
              ) : (
                <div className="px-4 py-2.5 flex flex-wrap items-center justify-between gap-3 bg-white text-[11px] font-mono">
                  <div className="flex flex-wrap items-center gap-5 text-[#1f1f1f]">
                    <div>
                      <div className="text-[9px] uppercase tracking-wider text-[#6b6b6b]">HEX</div>
                      <div>{c.hex}</div>
                    </div>
                    <div>
                      <div className="text-[9px] uppercase tracking-wider text-[#6b6b6b]">RGB</div>
                      <div>
                        {rgb.r}, {rgb.g}, {rgb.b}
                      </div>
                    </div>
                    <div>
                      <div className="text-[9px] uppercase tracking-wider text-[#6b6b6b]">
                        CMYK ({c.cmykMode.toUpperCase()})
                      </div>
                      <div>
                        {cmyk.c}, {cmyk.m}, {cmyk.y}, {cmyk.k}
                      </div>
                    </div>
                  </div>
                  <div className="flex items-center gap-5">
                    <ToggleSwitch
                      size="xs"
                      labelPosition="right"
                      checked={c.useAsLogo}
                      onChange={(v) => updateColor(c.id, { useAsLogo: v })}
                      label={t.useAsLogo}
                    />
                    <ToggleSwitch
                      size="xs"
                      labelPosition="right"
                      checked={c.useAsBackground}
                      onChange={(v) => updateColor(c.id, { useAsBackground: v })}
                      label={t.useAsBg}
                    />
                  </div>
                </div>
              )}
            </div>
          );
        })}
      </div>

      {/* Palette Import Dropzone (supports SVG, PDF, EPS!) + Add Color Button BELOW it */}
      <div className="space-y-3">
        <div
          role="button"
          tabIndex={0}
          onClick={() => paletteFileRef.current?.click()}
          onKeyDown={(e) => {
            if (e.key === 'Enter' || e.key === ' ') {
              e.preventDefault();
              paletteFileRef.current?.click();
            }
          }}
          onDragOver={(e) => {
            e.preventDefault();
            setIsDroppingPalette(true);
          }}
          onDragLeave={() => setIsDroppingPalette(false)}
          onDrop={(e) => {
            e.preventDefault();
            setIsDroppingPalette(false);
            handleImportPaletteFile(e.dataTransfer.files[0]);
          }}
          className={`rounded-2xl border-2 border-dashed p-6 text-center cursor-pointer transition ${
            isDroppingPalette
              ? 'border-[#fa5008] bg-[#fa5008]/5'
              : 'border-[#d6d2c8] bg-[hsl(40_16%_93%/0.4)] hover:border-[#fa5008] hover:bg-white'
          }`}
        >
          <input
            ref={paletteFileRef}
            type="file"
            accept=".svg,.pdf,.eps,image/svg+xml,application/pdf,application/postscript"
            className="hidden"
            onChange={(e) => {
              handleImportPaletteFile(e.target.files?.[0]);
              e.target.value = '';
            }}
          />
          <Upload className="mx-auto h-4 w-4 text-[#6b6b6b] mb-1.5" />
          <div className="text-xs font-medium text-[#1f1f1f]">
            {locale === 'ua'
              ? 'Перетягніть SVG, PDF або EPS-файл палітри чи лого сюди'
              : 'Drop your color palette file (SVG, PDF, EPS) here'}
          </div>
        </div>

        {paletteError && (
          <div className="rounded-lg border border-amber-200 bg-amber-50 px-3 py-2 text-xs text-amber-800 flex items-center gap-2">
            <AlertTriangle className="h-3.5 w-3.5 shrink-0" />
            <span>{paletteError}</span>
          </div>
        )}

        <div className="flex flex-wrap items-center justify-center gap-2.5">
          <button
            type="button"
            onClick={addManualColor}
            className="inline-flex items-center gap-1.5 rounded-full bg-[#1f1f1f] px-5 h-9 text-xs font-medium text-white hover:bg-[#333] transition shadow-2xs"
          >
            <Plus className="h-3.5 w-3.5" /> {t.addColor}
          </button>
          <button
            type="button"
            onClick={() => addHarmoniousColor('auto')}
            className="inline-flex items-center gap-1.5 rounded-full border border-[#e5e3dc] bg-white px-5 h-9 text-xs font-medium text-[#1f1f1f] hover:border-[#fa5008] transition shadow-2xs"
            title={
              locale === 'ua'
                ? 'Автоматично генерує гармонійний колір до вашої палітри й підбирає його назву'
                : 'Generate a harmonious matching color and auto-detect its name'
            }
          >
            <Sparkles className="h-3.5 w-3.5 text-[#fa5008]" />
            {locale === 'ua' ? 'Підібрати гармонійний колір' : 'Suggest matching color'}
          </button>
        </div>
      </div>

      {/* Live Logo x Background Preview */}
      {primaryAsset && logoInks.length > 0 && (
        <section className="rounded-xl border border-[#e5e3dc]/80 bg-[hsl(40_16%_93%/0.4)] p-5 space-y-3">
          <div className="text-[10px] uppercase tracking-widest font-semibold text-[#6b6b6b]">
            {t.liveColorPreview}
          </div>
          <div className="grid grid-cols-2 sm:grid-cols-3 md:grid-cols-4 gap-3.5">
            {logoInks.slice(0, 5).flatMap((ink) =>
              bgSwatches.slice(0, 4).map((bg) => {
                const ratio = contrastRatio(ink.hex, bg.hex);
                if (ratio < 1.3) return null;
                const recolored = recolorSvg(primaryAsset.svgContent, ink.hex, bg.hex);
                return (
                  <div
                    key={`${ink.id}__${bg.id}__${bg.hex}`}
                    className="rounded-xl border border-[#e5e3dc] bg-white overflow-hidden shadow-2xs"
                  >
                    <div
                      className="flex h-24 items-center justify-center p-4"
                      style={{ backgroundColor: bg.hex }}
                    >
                      <div
                        className="h-full w-full flex items-center justify-center [&>svg]:max-h-full [&>svg]:max-w-full [&>svg]:w-auto [&>svg]:h-auto"
                        dangerouslySetInnerHTML={{ __html: recolored }}
                      />
                    </div>
                    <div className="bg-white px-2.5 py-1.5 flex items-center justify-between text-[10px] font-mono text-[#6b6b6b] border-t border-[#eceae5]">
                      <span className="truncate">
                        {ink.name} / {bg.name}
                      </span>
                      <span className={ratio < 3 ? 'text-amber-600' : 'text-emerald-600'}>
                        {ratio.toFixed(1)}:1
                      </span>
                    </div>
                  </div>
                );
              }),
            )}
          </div>
        </section>
      )}

      {/* Footer Nav */}
      <div className="flex items-center justify-between pt-2">
        <button
          onClick={onBack}
          className="inline-flex items-center gap-2 rounded-full border border-[#e5e3dc] bg-white h-11 px-6 text-sm font-medium text-[#1f1f1f] shadow-2xs hover:bg-[#f8f6f1] transition"
        >
          <ArrowLeft className="h-4 w-4" /> {t.back}
        </button>
        <div className="flex items-center gap-3">
          <button
            onClick={onSkip}
            className="inline-flex items-center gap-1.5 rounded-full px-4 h-11 text-sm font-medium text-[#6b6b6b] hover:text-[#1f1f1f] transition"
          >
            <SkipForward className="h-4 w-4" /> {t.skip}
          </button>
          <button
            onClick={onNext}
            className="inline-flex items-center gap-2 rounded-full bg-[#fa5008] h-11 px-8 text-sm font-semibold text-white shadow-sm hover:bg-[#e04505]"
          >
            {t.next} <ArrowRight className="h-4 w-4" />
          </button>
        </div>
      </div>
    </div>
  );
};
